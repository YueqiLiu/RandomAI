// Refresh the public fallback only. No database credentials or private fields are used.
import {writeFile} from 'node:fs/promises';
const source='https://www.topaitools4u.site/api/tools';
const response=await fetch(source,{signal:AbortSignal.timeout(25000)});
if(!response.ok)throw new Error(`Catalog returned ${response.status}`);
const payload=await response.json();
if(!Array.isArray(payload.tools)||!payload.tools.length)throw new Error('No tools received; existing fallback was not changed');
const fields=['slug','name','category','description','website','url','pricing'];
const tools=payload.tools.map(tool=>Object.fromEntries(fields.filter(key=>typeof tool[key]==='string').map(key=>[key,tool[key]])));
const snapshot={source,syncedAt:new Date().toISOString(),tools};
await writeFile(new URL('../assets/catalog-snapshot.js',import.meta.url),'/* Public TopAITools4U catalog fallback; generated by scripts/sync-catalog.mjs. */\nwindow.RANDOM_AI_CATALOG='+JSON.stringify(snapshot).replaceAll('<','\\u003c')+';\n');
await writeFile(new URL('../assets/catalog-snapshot.json',import.meta.url),JSON.stringify(snapshot,null,2)+'\n');
console.log(`Synced ${tools.length} published tools`);
